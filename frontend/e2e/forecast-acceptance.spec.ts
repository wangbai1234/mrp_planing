import { expect, test } from '@playwright/test'

const base = 'http://localhost:5191'

test('经营计划只读验收：历史版本、差异搜索、空结果、导入弹窗', async ({ page, request }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const auth = await request.post(base + '/api/v1/auth/login', { data: { username: 'admin', password: 'admin123' } })
  expect(auth.ok(), await auth.text()).toBeTruthy()
  const login = (await auth.json()).data as { token: string; userId: number; username: string; displayName: string; roles: string[]; permissions: string[] }
  const current = await request.get(base + '/api/v1/forecast-workspace/current', { headers: { Authorization: 'Bearer ' + login.token } })
  expect(current.ok(), await current.text()).toBeTruthy()
  await page.goto(base + '/login')
  await page.evaluate(data => {
    localStorage.setItem('mrp_token', data.token)
    localStorage.setItem('mrp_user_info', JSON.stringify({ id: data.userId, username: data.username, displayName: data.displayName, roles: data.roles, permissions: data.permissions }))
  }, login)
  await page.goto(base + '/forecast')
  await expect(page.locator('.forecast-version-heading').getByText(/生效版本 V/)).toBeVisible()
  await expect(page.getByRole('button', { name: '返回最新版本' })).toHaveCount(0)
  await page.locator('.page-actions').getByRole('button', { name: '版本差异' }).click()
  const diff = page.getByRole('dialog', { name: /版本差异/ })
  await expect(diff).toBeVisible()
  await diff.getByPlaceholder('搜索料号/工厂').fill('FORECAST-API-1')
  await diff.locator('.el-checkbox').filter({ hasText: '显示未变化' }).click()
  await diff.getByRole('button', { name: '对比' }).click()
  await expect(diff.locator('.el-table__body tr').first()).toContainText('FORECAST-API-1')
  await diff.getByPlaceholder('搜索料号/工厂').fill('NO-SUCH-MATERIAL-987654321')
  await diff.getByRole('button', { name: '对比' }).click()
  await expect(diff.getByText('暂无版本差异')).toBeVisible()
  await diff.getByRole('button', { name: '关闭此对话框' }).click()

  await page.getByPlaceholder('搜索料号/名称/工厂').fill('NO-SUCH-MATERIAL-987654321')
  await page.locator('.forecast-table-header').getByRole('button', { name: '搜索' }).click()
  await expect(page.getByText('暂无经营计划数据')).toBeVisible()
  await page.getByPlaceholder('搜索料号/名称/工厂').clear()
  await page.locator('.forecast-table-header').getByRole('button', { name: '搜索' }).click()
  await expect(page.locator('.forecast-page > .el-card .el-table__body tr').first()).toBeVisible()

  await page.getByRole('button', { name: '查看版本' }).click()
  const history = page.getByRole('dialog', { name: '版本记录' })
  await expect(history.locator('.el-table__body tr').first()).toBeVisible()
  await history.locator('.el-table__body tr').last().getByRole('button', { name: '查看' }).click()
  await expect(page.getByRole('button', { name: '返回最新版本' })).toBeVisible()
  await expect(page.locator('.forecast-page > .el-card').getByRole('button', { name: '编辑' })).toHaveCount(0)
  await expect(page.locator('.forecast-page > .el-card').getByRole('button', { name: '删除' })).toHaveCount(0)
  await page.getByRole('button', { name: '返回最新版本' }).click()
  await expect(page.getByRole('button', { name: '返回最新版本' })).toHaveCount(0)

  await page.getByRole('button', { name: '导入', exact: true }).click()
  const upload = page.getByRole('dialog').filter({ hasText: '经营计划批量导入' })
  await expect(upload).toBeVisible()
  await expect(upload.getByText(/仅支持上传小于 30 MB/)).toHaveCount(2)
  await expect(upload.getByText(/30,000 条记录/)).toHaveCount(0)
  await upload.getByText('下载模板', { exact: true }).click()
  await expect(page.getByText('模板下载成功')).toBeVisible()
  await upload.locator('input[type=file]').setInputFiles({ name: 'invalid-forecast.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: Buffer.from('invalid workbook') })
  await expect(upload.getByText(/发现 .* 条错误数据，无法导入/)).toBeVisible()
  await expect(upload.getByRole('button', { name: '开始导入' })).toBeDisabled()
  await upload.getByRole('button', { name: '下载错误数据' }).click()
  await expect(page.getByText('错误报告下载成功')).toBeVisible()
  await upload.getByRole('button', { name: '关闭此对话框' }).click()
  expect(errors).toEqual([])
})
