import { expect, test } from '@playwright/test'

test('配置页面新增、编辑、查询日志、导入模板和删除', async ({ page }) => {
  test.setTimeout(120_000)
  const password = process.env.E2E_ADMIN_PASSWORD
  expect(password, 'E2E_ADMIN_PASSWORD').toBeTruthy()
  const suffix = Date.now().toString(36).toUpperCase()
  const factory = `UIT${suffix}`
  const warehouse = `UITW${suffix}`
  await page.goto('/login')
  await page.getByPlaceholder('邮箱').fill('admin')
  await page.getByPlaceholder('密码').fill(password!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login/)

  await page.goto('/mrp/factories')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '新增工厂' })
  await dialog.getByRole('textbox').nth(0).fill(factory)
  await dialog.getByRole('textbox').nth(1).fill('页面验收工厂')
  await dialog.getByRole('button', { name: '确认' }).click()
  const search = page.getByPlaceholder('搜索工厂编码或名称')
  await search.fill(factory.slice(2, 9))
  await search.press('Enter')
  const row = page.locator('.el-table__body tr').filter({ hasText: factory })
  await expect(row).toHaveCount(1)
  await row.getByRole('button', { name: '编辑' }).click()
  dialog = page.getByRole('dialog', { name: '编辑工厂' })
  await dialog.getByRole('textbox').nth(1).fill('页面验收工厂已改')
  await dialog.getByRole('button', { name: '确认' }).click()
  await expect(row).toContainText('页面验收工厂已改')
  await row.getByRole('button', { name: '查看日志' }).click()
  await expect(page.getByRole('dialog').first()).toBeVisible()
  await page.locator('.el-dialog:visible .el-dialog__headerbtn').click()

  await page.goto('/mrp/warehouses')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '新增仓库' })
  await dialog.locator('.el-form-item').filter({ hasText: '工厂' }).locator('.el-select').click()
  await page.getByRole('option', { name: factory }).click()
  await dialog.locator('.el-form-item').filter({ hasText: '仓库编码' }).getByRole('textbox').fill(warehouse)
  await dialog.locator('.el-form-item').filter({ hasText: '仓库名称' }).getByRole('textbox').fill('页面验收仓库')
  await dialog.getByRole('button', { name: '保存' }).click()
  const warehouseSearch = page.getByPlaceholder('搜索工厂或仓库')
  await warehouseSearch.fill(warehouse.slice(3, 10))
  await warehouseSearch.press('Enter')
  const warehouseRow = page.locator('.el-table__body tr').filter({ hasText: warehouse })
  await expect(warehouseRow).toHaveCount(1)
  await warehouseRow.getByRole('button', { name: '编辑' }).click()
  dialog = page.getByRole('dialog', { name: '编辑仓库' })
  await dialog.locator('.el-form-item').filter({ hasText: '仓库名称' }).getByRole('textbox').fill('页面验收仓库已改')
  await dialog.getByRole('button', { name: '保存' }).click()
  await expect(warehouseRow).toContainText('页面验收仓库已改')
  await warehouseRow.getByRole('button', { name: '查看日志' }).click()
  await expect(page.getByRole('dialog').first()).toBeVisible()
  await page.locator('.el-dialog:visible .el-dialog__headerbtn').click()
  await warehouseRow.getByRole('button', { name: '删除' }).click()
  await page.getByRole('dialog', { name: '删除仓库' }).getByRole('button', { name: '确定' }).click()
  await expect(warehouseRow).toHaveCount(0)

  await page.goto('/mrp/production-calendars')
  await page.locator('.filter-bar .el-select').first().click()
  await page.getByRole('option', { name: factory }).click()
  const currentMonth = new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Shanghai', year: 'numeric', month: '2-digit' }).slice(0, 7)
  const firstDay = `${currentMonth}-01`
  await page.getByRole('button', { name: `查看 ${firstDay} 配置` }).click()
  const dayDrawer = page.getByRole('dialog', { name: new RegExp(firstDay) })
  await dayDrawer.getByPlaceholder('正整数（台/日）').fill('3')
  await dayDrawer.getByRole('button', { name: '确认' }).click()
  await expect(dayDrawer).toBeHidden()
  await page.locator('.view-switch .el-radio-button').filter({ hasText: '列表' }).click()
  const dayRow = page.locator('.el-table__body tr').filter({ hasText: firstDay })
  await expect(dayRow).toContainText('3 台')
  await dayRow.getByRole('button', { name: '查看日志' }).click()
  await expect(page.getByRole('dialog').first()).toBeVisible()
  await page.locator('.el-dialog:visible .el-dialog__headerbtn').click()
  await dayRow.getByRole('button', { name: '删除' }).click()
  await page.getByRole('dialog', { name: '删除日期配置' }).getByRole('button', { name: '确认' }).click()
  await expect(dayRow).toContainText('未配置')
  await expect(dayRow.getByRole('button', { name: '删除' })).toHaveCount(0)

  for (const path of ['/mrp/warehouses', '/mrp/material-policies', '/mrp/stock-policies', '/mrp/production-calendars', '/mrp/business-weeks']) {
    await page.goto(path)
    await page.getByRole('button', { name: '导入', exact: true }).click()
    const importDialog = page.locator('.import-dialog:visible')
    await expect(importDialog).toBeVisible()
    const download = page.waitForEvent('download')
    await importDialog.getByText('下载模板', { exact: true }).click()
    const file = await download
    expect(file.suggestedFilename()).toMatch(/\.xlsx$/)
    await importDialog.locator('.el-dialog__headerbtn').click()
  }

  await page.goto('/mrp/factories')
  await search.fill(factory)
  await search.press('Enter')
  await row.getByRole('button', { name: '删除' }).click()
  await page.getByRole('dialog', { name: '删除工厂' }).getByRole('button', { name: '确定' }).click()
  await expect(row).toHaveCount(0)
})
