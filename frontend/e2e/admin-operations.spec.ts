import { expect, test } from '@playwright/test'

test('管理员完成角色、成员、用户和审计页面操作', async ({ page }) => {
  test.setTimeout(180_000)
  const password = process.env.E2E_ADMIN_PASSWORD
  expect(password, 'E2E_ADMIN_PASSWORD').toBeTruthy()
  const suffix = Date.now().toString(36)
  const roleCode = `ui_role_${suffix}`
  const roleName = `页面验收角色${suffix}`
  const copyCode = `${roleCode}_copy`
  const username = `ui_user_${suffix}`
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('response', response => {
    if (response.url().includes('/api/v1/') && response.status() >= 500) errors.push(`${response.status()} ${response.url()}`)
  })

  await page.goto('/login')
  await page.getByPlaceholder('邮箱').fill('admin')
  await page.getByPlaceholder('密码').fill(password!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login/)

  await page.goto('/admin/roles')
  await expect(page.locator('.role-list .el-pagination')).toBeVisible()
  await page.getByRole('button', { name: '新增', exact: true }).click()
  await page.getByPlaceholder('请输入角色编码').fill(roleCode)
  await page.getByPlaceholder('请输入角色名称').fill(roleName)
  await page.locator('.el-dialog:visible').getByRole('button', { name: '确认' }).click()
  await expect(page.getByText('创建成功')).toBeVisible()
  const search = page.getByPlaceholder('搜索角色名称/编码')
  await search.fill(roleCode.slice(3, 10))
  await search.press('Enter')
  const roleRow = page.locator('.role-list .el-table__body tr').filter({ has: page.getByRole('cell', { name: roleCode, exact: true }) })
  await expect(roleRow).toHaveCount(1)

  await roleRow.getByRole('button', { name: '编辑' }).click()
  await page.getByPlaceholder('请输入角色名称').fill(`${roleName}已改`)
  await page.locator('.el-dialog:visible').getByRole('button', { name: '确认' }).click()
  await expect(roleRow).toContainText(`${roleName}已改`)
  await roleRow.getByRole('button', { name: '查看成员' }).click()
  await expect(page.getByRole('dialog', { name: /角色成员/ })).toBeVisible()
  await expect(page.getByRole('dialog', { name: /角色成员/ }).getByText('暂无成员')).toBeVisible()
  await page.getByRole('dialog', { name: /角色成员/ }).locator('.el-dialog__headerbtn').click()

  await roleRow.getByRole('button', { name: '权限配置' }).click()
  await expect(page).toHaveURL(/\/permissions$/)
  await page.getByPlaceholder('搜索权限').fill('查看')
  await page.getByPlaceholder('搜索权限').press('Enter')
  await page.getByText('只显示已选').click()
  await page.getByRole('button', { name: '全部收起' }).click()
  await page.getByRole('button', { name: '全部展开' }).click()
  await page.getByText('全部工厂', { exact: true }).click()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('保存成功')).toBeVisible()

  await page.goto('/admin/roles')
  await search.fill(roleCode)
  await search.press('Enter')
  await roleRow.getByRole('button', { name: '复制' }).click()
  await page.getByPlaceholder('请输入新角色编码').fill(copyCode)
  await page.getByPlaceholder('请输入新角色名称').fill('页面验收副本')
  await page.locator('.el-dialog:visible').getByRole('button', { name: '确认复制' }).click()
  await expect(page.getByText('复制成功')).toBeVisible()
  await roleRow.getByRole('button', { name: '禁用' }).click()
  await expect(roleRow.getByRole('button', { name: '启用' })).toBeVisible()
  await roleRow.getByRole('button', { name: '启用' }).click()
  await expect(roleRow.getByRole('button', { name: '禁用' })).toBeVisible()

  await page.goto('/admin/users')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  await page.getByPlaceholder('请输入登录账号').fill(username)
  await page.getByPlaceholder('请输入用户姓名').fill('页面验收用户')
  await page.locator('.el-dialog:visible').getByRole('button', { name: '确认' }).click()
  await expect(page.getByRole('dialog', { name: '临时密码' })).toBeVisible()
  await page.getByRole('dialog', { name: '临时密码' }).getByRole('button', { name: '关闭', exact: true }).click()
  const userSearch = page.getByPlaceholder('搜索姓名/账号/部门')
  await userSearch.fill(username.slice(3, 11))
  await userSearch.press('Enter')
  const userRow = page.locator('.user-list .el-table__body tr').filter({ hasText: username })
  await expect(userRow).toHaveCount(1)
  await userRow.getByRole('button', { name: '编辑' }).click()
  await page.getByPlaceholder('请输入所属部门').fill('页面验收部门')
  await page.locator('.el-dialog:visible').getByRole('button', { name: '确认' }).click()
  await expect(userRow).toContainText('页面验收部门')
  await userRow.getByRole('button', { name: '分配角色' }).click()
  await page.getByRole('dialog', { name: '分配角色' }).getByText(`${roleName}已改`).click()
  await page.getByRole('dialog', { name: '分配角色' }).getByRole('button', { name: '确认' }).click()
  await expect(userRow).toContainText(`${roleName}已改`)
  await userRow.getByRole('button', { name: '禁用' }).click()
  await expect(userRow.getByRole('button', { name: '启用' })).toBeVisible()
  await userRow.getByRole('button', { name: '启用' }).click()
  await userRow.getByRole('button', { name: '重置密码' }).click()
  await page.getByRole('dialog', { name: '确认重置' }).getByRole('button', { name: '确定' }).click()
  await expect(page.getByRole('dialog', { name: '临时密码' })).toBeVisible()
  await page.getByRole('dialog', { name: '临时密码' }).getByRole('button', { name: '关闭', exact: true }).click()

  await page.goto('/admin/roles')
  await search.fill(roleCode)
  await search.press('Enter')
  await roleRow.getByRole('button', { name: '查看成员' }).click()
  await expect(page.getByRole('dialog', { name: /角色成员/ })).toContainText(username)
  await page.getByRole('dialog', { name: /角色成员/ }).locator('.el-dialog__headerbtn').click()

  await page.goto('/admin/users')
  await userSearch.fill(username)
  await userSearch.press('Enter')
  await userRow.getByRole('button', { name: '删除' }).click()
  await page.getByRole('dialog', { name: '确认删除' }).getByRole('button', { name: '确定' }).click()
  await expect(userRow).toHaveCount(0)

  await page.goto('/admin/roles')
  await search.fill(roleCode)
  await search.press('Enter')
  for (const code of [copyCode, roleCode]) {
    const row = page.locator('.role-list .el-table__body tr').filter({ has: page.getByRole('cell', { name: code, exact: true }) })
    await row.getByRole('button', { name: '删除' }).click()
    await page.getByRole('dialog', { name: '确认删除' }).getByRole('button', { name: '确定' }).click()
    await expect(row).toHaveCount(0)
  }

  await page.goto('/admin/audit-logs')
  await page.getByPlaceholder('搜索操作人/对象').fill(username)
  await page.getByPlaceholder('搜索操作人/对象').press('Enter')
  await page.getByPlaceholder('搜索操作人/对象').clear()
  await page.getByPlaceholder('搜索操作人/对象').press('Enter')
  await expect(page.locator('.audit-log .el-table__body tr').first().getByRole('button', { name: '查看' })).toBeVisible()
  await page.locator('.audit-log .el-table__body tr').first().getByRole('button', { name: '查看' }).click()
  await expect(page.locator('.el-dialog:visible, .el-drawer:visible').first()).toBeVisible()
  expect(errors).toEqual([])
})
